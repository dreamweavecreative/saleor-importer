-- Automation action ledger. Enables SAFE reactivation: only products the
-- automation itself withdrew may be automatically republished. Products
-- unpublished by an operator have no ledger row and are never touched.
-- Additive and idempotent. NOT executed by file creation.

CREATE TABLE IF NOT EXISTS catalogue.visibility_actions (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    canonical_product_id UUID NOT NULL
        REFERENCES catalogue.canonical_products(id) ON DELETE RESTRICT,
    saleor_product_id    TEXT,
    saleor_variant_id    TEXT,
    action               TEXT NOT NULL,
    reason               TEXT NOT NULL,
    actor                TEXT NOT NULL DEFAULT 'automation',
    created_at           TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT visibility_actions_action_ck
        CHECK (action IN ('WITHDRAW','REACTIVATE'))
);

CREATE INDEX IF NOT EXISTS visibility_actions_product_recent_idx
    ON catalogue.visibility_actions (canonical_product_id, created_at DESC);
CREATE INDEX IF NOT EXISTS visibility_actions_action_idx
    ON catalogue.visibility_actions (action, created_at DESC);
